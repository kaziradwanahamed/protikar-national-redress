from config.settings.base import *  # noqa: F401, F403
from config.settings.base import ALLOWED_HOSTS, env

DEBUG = False
SECURE_PROXY_SSL_HEADER = ("HTTP_X_FORWARDED_PROTO", "https")
SESSION_COOKIE_SECURE = True
CSRF_COOKIE_SECURE = True
SECURE_HSTS_SECONDS = 31536000
SECURE_HSTS_INCLUDE_SUBDOMAINS = True
SECURE_CONTENT_TYPE_NOSNIFF = True
X_FRAME_OPTIONS = "DENY"

# Render.com host and CSRF trust (RENDER_EXTERNAL_HOSTNAME is injected by Render)
RENDER_EXTERNAL_HOSTNAME = env("RENDER_EXTERNAL_HOSTNAME", default="")
RENDER_ALLOWED_HOSTS = [".onrender.com"]
if RENDER_EXTERNAL_HOSTNAME:
    RENDER_ALLOWED_HOSTS.append(RENDER_EXTERNAL_HOSTNAME)
ALLOWED_HOSTS = list(dict.fromkeys([*ALLOWED_HOSTS, *RENDER_ALLOWED_HOSTS]))

RENDER_TRUSTED_ORIGINS = ["https://*.onrender.com"]
if RENDER_EXTERNAL_HOSTNAME:
    RENDER_TRUSTED_ORIGINS.append(f"https://{RENDER_EXTERNAL_HOSTNAME}")
CSRF_TRUSTED_ORIGINS = list(
    dict.fromkeys([*env.list("CSRF_TRUSTED_ORIGINS", default=[]), *RENDER_TRUSTED_ORIGINS])
)
